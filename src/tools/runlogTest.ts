// OFFLINE test for the fleet run log.  `npm run log-test`
//
// The log exists to answer one question the seen-store cannot: is an agent quiet
// because there is nothing to send, or because it broke weeks ago? That makes
// the streak arithmetic load-bearing — a wrong count is worse than no count,
// because it would report a healthy fleet over a dead agent.
//
// The case most likely to be got wrong is the degraded run. When the free-tier
// quota runs out mid-run the agent reports 0, but that 0 is not evidence of
// anything. If a degraded run counted toward a zero-streak, one bad quota day
// would look exactly like the agent going silent — which is the failure this
// file is supposed to detect. These assertions pin that.
import { appendRun, loadRuns, render } from '../lib/runlog.js';
import { mkdtempSync, writeFileSync, existsSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

let pass = 0;
let fail = 0;
function check(name: string, cond: boolean): void {
  if (cond) {
    pass++;
    console.log(`  PASS  ${name}`);
  } else {
    fail++;
    console.log(`  FAIL  ${name}`);
  }
}

const dir = mkdtempSync(join(tmpdir(), 'runlog-'));
const log = join(dir, 'run-log.jsonl');
const idx = join(dir, 'AGENT-LOG.md');

const NOW = Date.parse('2026-10-15T06:00:00Z');
const daysAgo = (d: number): Date => new Date(NOW - d * 864e5);

// ---------------------------------------------------------------------------
console.log('\n--- appendRun records a run and writes the index ---');
check('append returns true', appendRun({ agent: 'job', reported: 3, found: 41 }, { logPath: log, indexPath: idx, now: daysAgo(0) }));
check('log file exists', existsSync(log));
check('index file exists', existsSync(idx));
check('one line written', readFileSync(log, 'utf8').trim().split('\n').length === 1);
const parsed = loadRuns(log);
check('the entry round-trips', parsed.length === 1 && parsed[0].agent === 'job' && parsed[0].reported === 3);
check('a timestamp was stamped on', typeof parsed[0]?.ts === 'string' && parsed[0].ts.startsWith('2026-10-15'));

// ---------------------------------------------------------------------------
console.log('\n--- a dry run is a rehearsal, not an event ---');
const beforeDry = loadRuns(log).length;
check('append returns false for a dry run', appendRun({ agent: 'job', reported: 0, dryRun: true }, { logPath: log, indexPath: idx, now: daysAgo(0) }) === false);
check('nothing was recorded', loadRuns(log).length === beforeDry);

// ---------------------------------------------------------------------------
console.log('\n--- the index has an index on top (the whole point) ---');
const md = render(log, NOW);
check('has a title', md.includes('# Agent fleet log'));
check('Index section comes before Detail', md.indexOf('## Index') < md.indexOf('## Detail'));
check('has the index table header', md.includes('| When (UTC) | Agent | Found | Screened | Reported | Status |'));
check('marks itself as generated', md.includes('GENERATED by src/lib/runlog.ts'));
check('labelled UTC, not implied local', md.includes('Times are UTC'));
check('a normal run reads "ok"', md.includes('| ok |'));

// ---------------------------------------------------------------------------
console.log('\n--- "nothing new" and "nothing matched" are different zeros ---');
// Added 2026-10-16. Every agent returns early when the seen-store has already
// absorbed everything the boards returned, and that return happens BEFORE any
// screening — so a run that screened nothing used to be logged with the reason
// "nothing passed screening", which describes a screen that never ran. The two
// zeros need opposite fixes (widen the sources vs. loosen the criteria), so the
// funnel has to be in the record.
const z = mkdtempSync(join(tmpdir(), 'runlog-screened-'));
const zl = join(z, 'l.jsonl');
const zi = join(z, 'i.md');
appendRun({ agent: 'job', found: 37, screened: 0, reported: 0, reason: 'Nothing was screened: every candidate the boards returned was already in the seen-store.' }, { logPath: zl, indexPath: zi, now: daysAgo(1) });
appendRun({ agent: 'job', found: 37, screened: 37, reported: 0, reason: 'Nothing passed screening and link verification today.' }, { logPath: zl, indexPath: zi, now: daysAgo(0) });
const zmd = render(zl, NOW);
check('the funnel is rendered with screened in it', zmd.includes('| 2026-10-15 06:00 | job | 37 | 37 | 0 | nothing sent |'));
check('a zero-screened run is visible as such', zmd.includes('| 2026-10-14 06:00 | job | 37 | 0 | 0 | nothing sent |'));
check('the index explains what screened 0 means', zmd.includes('is not a quiet day'));
check('the reason survives into the detail', zmd.includes('already in the seen-store'));
check('screened round-trips through the log', loadRuns(zl).some((x) => x.screened === 0));

// ---------------------------------------------------------------------------
console.log('\n--- status is distinguishable, because "quiet" and "broken" are not the same ---');
appendRun({ agent: 'research', reported: 0 }, { logPath: log, indexPath: idx, now: daysAgo(1) });
appendRun({ agent: 'content', reported: 0, degraded: true }, { logPath: log, indexPath: idx, now: daysAgo(1) });
const md2 = render(log, NOW);
check('a zero-report run reads "nothing sent"', md2.includes('| nothing sent |'));
check('a quota-hit run reads "degraded"', md2.includes('| degraded |'));

// ---------------------------------------------------------------------------
console.log('\n--- streak: consecutive zero-report runs, newest first ---');
const s = mkdtempSync(join(tmpdir(), 'runlog-streak-'));
const sl = join(s, 'l.jsonl');
const si = join(s, 'i.md');
for (const d of [6, 5, 4, 3, 2, 1, 0]) {
  appendRun({ agent: 'scholarship', reported: 0, found: 20 }, { logPath: sl, indexPath: si, now: daysAgo(d) });
}
const smd = render(sl, NOW);
check('a 7-run silence is flagged', smd.includes('Worth a look'));
check('the flag names the agent', /scholarship\*\* has reported nothing for \*\*7 consecutive runs/.test(smd));
check('the flag says never-sent when that is true', smd.includes('has never sent anything'));
check('health row shows the streak', /\| scholarship \| 2026-10-15 \| 0 \| 7 \| 0 \| never \|/.test(smd));

// ---------------------------------------------------------------------------
console.log('\n--- a degraded run must NOT count as a zero ---');
// This is the case that matters. Two real zeros, then a quota failure, then a
// real zero: the streak is 3, not 4. Counting the degraded run would make a
// quota outage look like the agent went quiet.
const g = mkdtempSync(join(tmpdir(), 'runlog-deg-'));
const gl = join(g, 'l.jsonl');
const gi = join(g, 'i.md');
appendRun({ agent: 'job', reported: 0 }, { logPath: gl, indexPath: gi, now: daysAgo(5) });
appendRun({ agent: 'job', reported: 0 }, { logPath: gl, indexPath: gi, now: daysAgo(4) });
appendRun({ agent: 'job', reported: 0, degraded: true }, { logPath: gl, indexPath: gi, now: daysAgo(3) });
appendRun({ agent: 'job', reported: 0 }, { logPath: gl, indexPath: gi, now: daysAgo(2) });
const gmd = render(gl, NOW);
check('degraded run excluded → streak is 3, not 4', /\| job \| 2026-10-13 \| 0 \| 3 \| 0 \| never \|/.test(gmd));
check('3 is below the alert threshold → not flagged', !gmd.includes('Worth a look'));

// ---------------------------------------------------------------------------
console.log('\n--- a real report resets the streak ---');
const r = mkdtempSync(join(tmpdir(), 'runlog-reset-'));
const rl = join(r, 'l.jsonl');
const ri = join(r, 'i.md');
appendRun({ agent: 'job', reported: 0 }, { logPath: rl, indexPath: ri, now: daysAgo(9) });
appendRun({ agent: 'job', reported: 2 }, { logPath: rl, indexPath: ri, now: daysAgo(2) });
appendRun({ agent: 'job', reported: 0 }, { logPath: rl, indexPath: ri, now: daysAgo(0) });
const rmd = render(rl, NOW);
check('streak counted only from the newest zero', /\| job \| 2026-10-15 \| 0 \| 1 \| 0 \| 2026-10-13 \(2d ago\) \|/.test(rmd));
check('last non-zero is reported with its age', rmd.includes('(2d ago)'));

// ---------------------------------------------------------------------------
console.log('\n--- never throws: a corrupt log must not take down a real run ---');
const c = mkdtempSync(join(tmpdir(), 'runlog-corrupt-'));
const cl = join(c, 'l.jsonl');
const ci = join(c, 'i.md');
appendRun({ agent: 'job', reported: 1 }, { logPath: cl, indexPath: ci, now: daysAgo(0) });
// Simulate a process killed mid-append: a half-written line at the tail.
writeFileSync(cl, readFileSync(cl, 'utf8') + '{"agent":"job","rep');
let survived = true;
try {
  appendRun({ agent: 'job', reported: 1 }, { logPath: cl, indexPath: ci, now: daysAgo(0) });
} catch {
  survived = false;
}
check('a half-written line does not throw', survived);
check('the half-written line is not counted as a run', loadRuns(cl).every((x) => typeof x.reported === 'number'));

console.log('\n--- never throws: an unwritable path returns false ---');
let threw = false;
let ok = true;
try {
  ok = appendRun({ agent: 'job', reported: 1 }, { logPath: '/proc/nope/denied/x.jsonl', indexPath: '/proc/nope/denied/i.md' });
} catch {
  threw = true;
}
check('does not throw on an unwritable path', !threw);
check('returns false instead', ok === false);

// ---------------------------------------------------------------------------
console.log('\n--- a thrown pass is not a quiet day (the live 401 case) ---');
// Found for real on 2026-10-15: the Job agent's Gemini key returned HTTP 401
// ("service account is deleted or disabled") on both passes. safeRun swallowed
// it, the agent sent "No new qualifying opportunities today", and `degraded`
// stayed false because a 401 is not a quota error. Recorded naively, that is a
// clean-looking "nothing sent" — a dead agent wearing a quiet day's clothes.
const a = mkdtempSync(join(tmpdir(), 'runlog-abort-'));
const al = join(a, 'l.jsonl');
const ai = join(a, 'i.md');
const AUTH_ERR = 'JOB: Gemini HTTP 401: {"error":{"code":401,"status":"UNAUTHENTICATED"}}';
for (const d of [3, 2, 1, 0]) {
  appendRun(
    { agent: 'job', reported: 0, found: 40, aborted: [AUTH_ERR], reason: 'A pass threw before it could screen anything — this zero is not real information.' },
    { logPath: al, indexPath: ai, now: daysAgo(d) },
  );
}
const amd = render(al, NOW);
check('an aborted run reads "aborted", not "nothing sent"', amd.includes('| aborted |'));
check('it does not read "nothing sent"', !amd.includes('| nothing sent |'));
check('failed runs are counted separately', /\| job \| 2026-10-15 \| 0 \| 0 \| 4 \| never \|/.test(amd));
check('a four-day outage is flagged', amd.includes('has failed to complete **4 consecutive runs**'));
check('the flag carries the actual error', amd.includes('Gemini HTTP 401'));
check('the flag refuses to call it idle', amd.includes('it is broken'));
check('the error is rendered in the detail', amd.includes('failed: `JOB: Gemini HTTP 401'));
// The trap this guards: every run aborts, so nothing ever *completes*, so a
// zero-streak of 0 would report a dead fleet as healthy.
check('a fully-aborted agent is NOT reported as healthy', !amd.includes('Nothing to flag'));

console.log('\n--- ONE failure is reported, not swallowed ---');
// Found by reading this file's own output from a real run on 2026-10-16. A job
// run aborted with HTTP 401; the abort-streak was 1, so no flag fired, and the
// index closed with "Nothing flagged. Every agent that has run recently has sent
// something." — a false sentence in the first place a reader looks. A single
// failure is now a heads-up rather than silence.
const one = mkdtempSync(join(tmpdir(), 'runlog-onefail-'));
const ol = join(one, 'l.jsonl');
const oi = join(one, 'i.md');
appendRun({ agent: 'job', reported: 2, found: 40, screened: 20 }, { logPath: ol, indexPath: oi, now: daysAgo(1) });
appendRun({ agent: 'job', reported: 0, found: 45, screened: 14, aborted: [AUTH_ERR] }, { logPath: ol, indexPath: oi, now: daysAgo(0) });
const omd = render(ol, NOW);
check('a single failure is surfaced', omd.includes('below the alert threshold'));
check('it names the agent that failed', omd.includes('**job** failed its most recent run'));
check('it carries the error', omd.includes('Gemini HTTP 401'));
check('it does NOT claim the fleet is clean', !omd.includes('Nothing to flag'));
check('it is not escalated to "Worth a look" yet', !omd.includes('**Worth a look:**'));
// The funnel is what makes the entry readable: 14 candidates reached the AI and
// the call then failed, which is a different situation from never reaching it.
check('the funnel records candidates that reached the AI', omd.includes('| job | 45 | 14 | 0 | aborted |'));

console.log('\n--- a clean fleet still says so ---');
const cl2 = mkdtempSync(join(tmpdir(), 'runlog-clean-'));
const cll = join(cl2, 'l.jsonl');
const cli = join(cl2, 'i.md');
appendRun({ agent: 'job', reported: 3, found: 40, screened: 20 }, { logPath: cll, indexPath: cli, now: daysAgo(1) });
appendRun({ agent: 'research', reported: 2, found: 30, screened: 30 }, { logPath: cll, indexPath: cli, now: daysAgo(0) });
const clmd = render(cll, NOW);
check('an actually-clean fleet reports itself clean', clmd.includes('Nothing to flag'));
check('and does not claim more than it checked', clmd.includes('most recent run completed'));

console.log('\n--- aborted runs do not extend the silent-run streak either ---');
const b = mkdtempSync(join(tmpdir(), 'runlog-abort2-'));
const bl = join(b, 'l.jsonl');
const bi = join(b, 'i.md');
appendRun({ agent: 'research', reported: 0 }, { logPath: bl, indexPath: bi, now: daysAgo(3) });
appendRun({ agent: 'research', reported: 0, aborted: [AUTH_ERR] }, { logPath: bl, indexPath: bi, now: daysAgo(2) });
appendRun({ agent: 'research', reported: 0 }, { logPath: bl, indexPath: bi, now: daysAgo(1) });
const bmd = render(bl, NOW);
// Two completed zero-runs with an aborted one between them: the silent streak is
// 2, not 3. The abort is not counted as a silent run. The abort-streak is 0
// because the newest run completed — a past failure is not a current outage.
check('silent runs counted as 2 (the abort is not one of them)', /\| research \| 2026-10-14 \| 0 \| 2 \| 0 \| never \|/.test(bmd));

// ---------------------------------------------------------------------------
console.log('\n--- pruning: the log cannot grow without bound ---');
const p = mkdtempSync(join(tmpdir(), 'runlog-prune-'));
const pl = join(p, 'l.jsonl');
const pi = join(p, 'i.md');
appendRun({ agent: 'job', reported: 1 }, { logPath: pl, indexPath: pi, now: daysAgo(400) });
appendRun({ agent: 'job', reported: 1 }, { logPath: pl, indexPath: pi, now: daysAgo(1) });
check('the 400-day-old run is dropped', loadRuns(pl).length === 1);

// ---------------------------------------------------------------------------
console.log('\n--- empty state is readable, not blank ---');
const e = mkdtempSync(join(tmpdir(), 'runlog-empty-'));
const emd = render(join(e, 'nothing.jsonl'), NOW);
check('says so instead of rendering a broken table', emd.includes('No runs recorded yet'));
check('still names the fleet', emd.includes('# Agent fleet log'));

for (const d of [dir, s, g, r, c, p, e, z, one, cl2]) {
  try {
    rmSync(d, { recursive: true, force: true });
  } catch {
    /* a leftover temp dir is not worth failing the suite over */
  }
}

console.log(`\nRESULT: ${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
